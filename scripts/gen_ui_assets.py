def digit_glyph(char):
    width = NARROW_W if char in NARROW else DIGIT_W
    margin = DIGIT_PEN / 2 + 0.5
    scale_y = (DIGIT_H - 2 * margin) / 18
    scale_x = (DIGIT_W - 2 * margin) / 10
    offset_x = margin - (DIGIT_W - width) / 2 if char in NARROW else margin
    strokes = [[(offset_x + x * scale_x, margin + y * scale_y) for x, y in line]
               for line in DIGIT_SHAPES[char]]
    return rasterize(DIGIT_W, DIGIT_H, strokes, pen=DIGIT_PEN)


