def parse_font(text, width, height):
    glyphs = {}
    current = None
    for line in text.strip('\n').split('\n'):
        if line.startswith('>'):
            current = ' ' if line == '>' else line[1:]
            if len(current) != 1 or current in glyphs:
                raise ValueError(f'bad glyph header {line!r}')
            glyphs[current] = []
            continue
        if len(line) != width or not set(line) <= set('#.'):
            raise ValueError(f'glyph {current!r}: row {line!r} is not {width} wide')
        glyphs[current].append(line)
    for char in map(chr, range(32, 127)):
        rows = glyphs.get(char)
        if rows is None:
            raise ValueError(f'missing glyph {char!r}')
        if len(rows) > height:
            raise ValueError(f'glyph {char!r} has {len(rows)} rows, limit {height}')
        rows.extend(['.' * width] * (height - len(rows)))
    return glyphs


# Vector rasterizer: strokes are polylines with a round pen, fills are polygons.
def _segment_distance(px, py, ax, ay, bx, by):
    dx, dy = bx - ax, by - ay
    length = dx * dx + dy * dy
    t = 0.0 if length == 0 else max(0.0, min(1.0, ((px - ax) * dx + (py - ay) * dy) / length))
    return math.hypot(px - (ax + t * dx), py - (ay + t * dy))


def _inside(px, py, polygon):
    inside = False
    for (ax, ay), (bx, by) in zip(polygon, polygon[1:] + polygon[:1]):
        if (ay > py) != (by > py) and px < ax + (py - ay) * (bx - ax) / (by - ay):
            inside = not inside
    return inside


def rasterize(width, height, strokes=(), fills=(), pen=2.0, samples=4):
    segments = [(a, b) for line in strokes for a, b in zip(line, line[1:] or line)]
    rows = []
    for y in range(height):
        row = ''
        for x in range(width):
            hits = 0
            for sy in range(samples):
                for sx in range(samples):
                    px, py = x + (sx + 0.5) / samples, y + (sy + 0.5) / samples
                    if any(_segment_distance(px, py, *a, *b) <= pen / 2 for a, b in segments) \
                            or any(_inside(px, py, poly) for poly in fills):
                        hits += 1
            row += '#' if hits * 2 >= samples * samples else '.'
        rows.append(row)
    return rows


def arc(cx, cy, rx, ry, start, end, steps=24):
    """Points along an ellipse; angles in degrees, counter-clockwise, y down."""
    return [(cx + rx * math.cos(math.radians(start + (end - start) * i / steps)),
             cy - ry * math.sin(math.radians(start + (end - start) * i / steps)))
            for i in range(steps + 1)]


