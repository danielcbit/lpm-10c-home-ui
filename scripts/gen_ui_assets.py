def pack(rows):
    width = len(rows[0])
    stride = (width + 7) // 8
    data = []
    for row in rows:
        bits = int(row.replace('#', '1').replace('.', '0').ljust(stride * 8, '0'), 2)
        data.extend(bits.to_bytes(stride, 'big'))
    return data


def c_bytes(data, indent='    '):
    return '\n'.join(indent + ' '.join(f'0x{b:02x},' for b in data[i:i + 12])
                     for i in range(0, len(data), 12))


def c_char(char):
    return {'\\': 'backslash', "'": 'quote', '*': 'asterisk', '/': 'slash'}.get(char, char)


def font_block(name, glyphs, width, height, line_height, advance=None, chars=None):
    chars = chars or [chr(c) for c in range(32, 127)]
    lines = [f'static const uint8_t {name}_bits[] = {{']
    for char in chars:
        lines.append(f'    /* {c_char(char)} */')
        lines.append(c_bytes(pack(glyphs[char]), '    '))
    lines.append('};')
    adv = 'NULL'
    if advance:
        lines.append(f'static const uint8_t {name}_advance[] = {{')
        lines.append(c_bytes([advance[c] for c in chars]))
        lines.append('};')
        adv = f'{name}_advance'
    lines.append(f'const lpm_font {name} = {{{ord(chars[0])}, {len(chars)}, {width}, {height}, '
                 f'{width + 1}, {line_height}, {adv}, {name}_bits}};')
    return '\n'.join(lines)


def generate(out_dir):
    small = parse_font(SMALL_FONT, 5, 9)
    body = parse_font(BODY_FONT, 7, 11)
    # Digits font covers ' ' through ':' (space, '-', '.', digits, ':').
    digit_chars = [chr(c) for c in range(ord(' '), ord(':') + 1)]
    digits = {c: (digit_glyph(c) if c in DIGIT_SHAPES else ['.' * DIGIT_W] * DIGIT_H) for c in digit_chars}
    advance = {c: (NARROW_W if c in NARROW else DIGIT_W + 2) for c in digit_chars}
    icons = {name: rasterize(24, 24, spec.get('strokes', ()), spec.get('fills', ()), spec.get('pen', 2.0))
             for name, spec in ICONS.items()}

    header = ['/* Generated by scripts/gen_ui_assets.py; do not edit. */',
              '#ifndef LPM_ASSETS_H', '#define LPM_ASSETS_H', '', '#include "lpm_gfx.h"', '',
              'extern const lpm_font lpm_font_small;  /* 5x9 glyphs, 12 px line */',
              'extern const lpm_font lpm_font_body;   /* 7x11 glyphs, 16 px line */',
              'extern const lpm_font lpm_font_digits; /* 16x28 numerals, 32 px line */', '']
    header += [f'extern const lpm_icon lpm_icon_{name};' for name in icons]
    header += ['', '#endif', '']
    source = ['/* Generated by scripts/gen_ui_assets.py; do not edit. */', '#include "lpm_assets.h"', '',
              '#include <stddef.h>', '',
              font_block('lpm_font_small', small, 5, 9, 12), '',
              font_block('lpm_font_body', body, 7, 11, 16), '',
              font_block('lpm_font_digits', digits, DIGIT_W, DIGIT_H, 32, advance, digit_chars), '']
    for name, rows in icons.items():
        preview = '\n'.join(f' * {row}' for row in rows)
        source += [f'/*\n{preview}\n */', f'static const uint8_t lpm_icon_{name}_bits[] = {{',
                   c_bytes(pack(rows)), '};',
                   f'const lpm_icon lpm_icon_{name} = {{24, 24, lpm_icon_{name}_bits}};', '']
    (out_dir / 'lpm_assets.h').write_text('\n'.join(header))
    (out_dir / 'lpm_assets.c').write_text('\n'.join(source))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
