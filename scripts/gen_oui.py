def load(path):
    prefixes = {}
    with open(path, newline='', encoding='utf-8') as f:
        for row in csv.DictReader(f):
            if row['Registry'] != 'MA-L':
                continue
            org = row['Organization Name'].strip()
            for name, pattern in BRANDS.items():
                if re.match(pattern, org, re.IGNORECASE):
                    prefixes[int(row['Assignment'], 16)] = name
                    break
    return prefixes


# Entries (4 bytes each) per chunk: the first four fill freed vendor pictures that home_ui.ld maps as
# OUI1-OUI4; the last, the rest, goes with the other added data.
CHUNKS = (3954, 2441, 2348, 2017)


def generate(prefixes, out):
    names = sorted(set(prefixes.values()))
    keys = sorted(prefixes)
    bounds, start = [], 0
    for size in CHUNKS:
        bounds.append((start, min(start + size, len(keys))))
        start = min(start + size, len(keys))
    bounds.append((start, len(keys)))
    lines = ['/* Generated by scripts/gen_oui.py from the IEEE MA-L registry; do not edit. */',
             '#include <stdint.h>', '', '#include "oui_table.h"', '',
             f'const char *const lpm_oui_names[{len(names)}] = {{']
    lines += [f'    "{n}",' for n in names]
    lines += ['};', '']
    for c, (a, b) in enumerate(bounds):
        lines.append(f'/* Prefixes {a}-{b - 1}: three bytes, then the index of the name. */')
        lines.append(f'static const uint8_t lpm_oui_{c + 1}[{max(b - a, 1)}][4] = {{')
        rows = [f'{{0x{k >> 16:02x}, 0x{k >> 8 & 255:02x}, 0x{k & 255:02x}, {names.index(prefixes[k])}}},'
                for k in keys[a:b]] or ['{0xff, 0xff, 0xff, 0},']
        for i in range(0, len(rows), 5):
            lines.append('    ' + ' '.join(rows[i:i + 5]))
        lines += ['};', '']
    lines.append(f'const lpm_oui_chunk lpm_oui_chunks[LPM_OUI_CHUNKS] = {{')
    lines += [f'    {{lpm_oui_{c + 1}, {b - a}}},' for c, (a, b) in enumerate(bounds)]
    lines += ['};', '']
    out.write_text('\n'.join(lines))
    header = out.with_suffix('.h')
    header.write_text('\n'.join([
        '/* Generated by scripts/gen_oui.py; do not edit. */', '#ifndef LPM_OUI_TABLE_H', '#define LPM_OUI_TABLE_H',
        '', '#include <stdint.h>', '', f'#define LPM_OUI_CHUNKS {len(bounds)}', '',
        '/* Sorted prefixes, each {three bytes, name index}; the chunks follow each other in order. */',
        'typedef struct {', '    const uint8_t (*entries)[4];', '    uint16_t count;', '} lpm_oui_chunk;', '',
        f'extern const char *const lpm_oui_names[{len(names)}];',
        'extern const lpm_oui_chunk lpm_oui_chunks[LPM_OUI_CHUNKS];', '', '#endif', '']))
    return len(keys), len(names)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('registry', type=Path, help='oui.csv from the IEEE')
    parser.add_argument('--out', type=Path, default=ROOT / 'src' / 'firmware_patch' / 'oui_table.c')
    parser.add_argument('--counts', action='store_true', help='print the prefixes per brand and stop')
    args = parser.parse_args()
    prefixes = load(args.registry)
    if args.counts:
        counts = {}
        for name in prefixes.values():
            counts[name] = counts.get(name, 0) + 1
        for name, n in sorted(counts.items(), key=lambda item: -item[1]):
            print(f'{n:5} {name}')
        missing = sorted(set(BRANDS) - set(counts))
        print(f'{len(prefixes)} prefixes, {len(counts)} brands; none for: {", ".join(missing) or "-"}')
        return
    n, names = generate(prefixes, args.out)
    print(f'Wrote {args.out}: {n} prefixes of {names} manufacturers, {n * 4} bytes')


if __name__ == '__main__':
    main()
